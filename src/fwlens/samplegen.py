"""Synthetic traffic logs for the sample configs.

Run:  uv run python -m fwlens.samplegen    (rewrites data/samples/logs/*.log)

Deterministic: a fixed seed and a fixed time window, so the committed logs can be
regenerated byte-for-byte (a test checks that). For each rule that should see traffic,
sessions are built from the rule's own match fields, then written in the vendor's format.
"""

import random
from datetime import UTC, datetime, timedelta
from ipaddress import IPv4Network, IPv6Network, ip_address, ip_network
from pathlib import Path

from fwlens.models import (
    ANY,
    Action,
    AddressObject,
    LogEvent,
    ParsedConfig,
    Rule,
    ServiceObject,
    Vendor,
)
from fwlens.parsers.fortigate import parse_fortigate_file
from fwlens.parsers.panos import parse_panos_file
from fwlens.parsers.syslog import PANOS_FIELDS, PANOS_MIN_FIELDS, PANOS_TIME_FORMAT

SAMPLES = Path(__file__).resolve().parents[2] / "data" / "samples"
SEED = 42
EVENTS_PER_DEVICE = 1000
WINDOW_START = datetime(2026, 10, 25, tzinfo=UTC)
WINDOW = timedelta(days=7)

# Rules with no traffic in the window, and why. Ground truth for the zero-hit check.
# Disabled rules and rules with logging off also produce no log lines; the latter still
# carry traffic, which is exactly the trap the zero-hit check has to report honestly.
NO_TRAFFIC = {
    "allow-ssh-jump": "shadowed: allow-ssh-admins matches the same traffic first",
    "allow-web-out-copy": "duplicate: allow-web-out matches the same traffic first",
    "drop-blocklist": "no blocklisted source showed up this week",
    "deny-blocklist": "no blocklisted source showed up this week",
}
WEIGHTS = {"allow-web-out": 30, "allow-dns": 20, "allow-web-in": 15, "deny-all": 10}
DEFAULT_WEIGHT = 3

# Stand-ins for "any": documentation ranges for the internet side.
ANY_SRC = ip_network("203.0.113.0/24")
ANY_DST = ip_network("192.0.2.0/24")
COMMON_PORTS = [("tcp", 443), ("tcp", 80), ("tcp", 22), ("udp", 53)]
# PAN-OS "application-default": the app's standard port.
APP_PORTS = {
    "dns": ("udp", 53),
    "web-browsing": ("tcp", 80),
    "ssl": ("tcp", 443),
    "ssh": ("tcp", 22),
    "ntp": ("udp", 123),
    "ftp": ("tcp", 21),
}

# ---------------------------------------------------------------------------
# Building sessions
# ---------------------------------------------------------------------------


def generate_events(
    config: ParsedConfig, rng: random.Random, count: int = EVENTS_PER_DEVICE
) -> list[tuple[Rule, LogEvent]]:
    """`count` sessions spread over the window, sorted by time, each paired with its rule."""
    addresses = {a.name: a for a in config.addresses}
    services = {s.name: s for s in config.services}
    active = [r for r in config.rules if r.enabled and r.log and r.name not in NO_TRAFFIC]
    weights = [WEIGHTS.get(r.name, DEFAULT_WEIGHT) for r in active]

    pairs = []
    for rule in rng.choices(active, weights, k=count):
        protocol, port = _pick_port(rng, rule, services)
        blocked = rule.action is not Action.ALLOW
        event = LogEvent(
            vendor=config.vendor,
            device=config.device,
            timestamp=WINDOW_START + timedelta(seconds=rng.randrange(int(WINDOW.total_seconds()))),
            src_ip=_pick_ip(rng, rule.src_addrs, addresses, ANY_SRC),
            dst_ip=_pick_ip(rng, rule.dst_addrs, addresses, ANY_DST),
            dst_port=port,
            protocol=protocol,
            rule_name=rule.name,
            action=rule.action,
            bytes=rng.randint(0, 120) if blocked else rng.randint(200, 50_000),
        )
        pairs.append((rule, event))
    return sorted(pairs, key=lambda pair: pair[1].timestamp)


Network = IPv4Network | IPv6Network


def _pick_ip(
    rng: random.Random,
    names: tuple[str, ...],
    addresses: dict[str, AddressObject],
    fallback: Network,
) -> str:
    name = rng.choice(names)
    obj = addresses.get(name)
    values = obj.resolved if obj and name != ANY else ()
    candidates = [ip for v in values if (ip := _ip_in(rng, v))]
    return rng.choice(candidates) if candidates else _host_in(rng, fallback)


def _ip_in(rng: random.Random, value: str) -> str | None:
    """A random IP inside a CIDR or range; None for an FQDN."""
    if "/" in value:
        return _host_in(rng, ip_network(value, strict=False))
    if "-" in value:
        start, end = (int(ip_address(part)) for part in value.split("-"))
        return str(ip_address(rng.randint(start, end)))
    return None


def _host_in(rng: random.Random, network: Network) -> str:
    if network.num_addresses <= 2:  # /32, /31: every address is usable
        return str(network.network_address + rng.randrange(network.num_addresses))
    return str(network.network_address + rng.randrange(1, network.num_addresses - 1))


def _pick_port(
    rng: random.Random, rule: Rule, services: dict[str, ServiceObject]
) -> tuple[str, int | None]:
    name = rng.choice(rule.services)
    if name == "application-default":
        app = rng.choice(rule.applications)
        return APP_PORTS.get(app) or rng.choice(COMMON_PORTS)
    obj = services.get(name)
    if name == ANY or obj is None:
        return rng.choice(COMMON_PORTS)
    entry = rng.choice(obj.resolved)  # "tcp/443", "tcp/8000-8080", "icmp", "ip"
    if "/" not in entry:
        return ("icmp", None) if entry.startswith("icmp") else rng.choice(COMMON_PORTS)
    protocol, ports = entry.split("/")
    return protocol, int(ports.split("-")[0])


# ---------------------------------------------------------------------------
# Writing log lines
# ---------------------------------------------------------------------------


def panos_line(event: LogEvent, subtype: str | None = None) -> str:
    """A PAN-OS TRAFFIC log in syslog form. Fields we don't model are left empty."""
    fields = [""] * PANOS_MIN_FIELDS
    values = {
        "type": "TRAFFIC",
        "subtype": subtype or ("end" if event.action is Action.ALLOW else event.action.value),
        "generated_time": event.timestamp.strftime(PANOS_TIME_FORMAT),
        "src_ip": str(event.src_ip),
        "dst_ip": str(event.dst_ip),
        "rule": event.rule_name,
        "dst_port": str(event.dst_port or 0),
        "protocol": event.protocol,
        "action": event.action.value,
        "bytes": str(event.bytes),
    }
    for name, value in values.items():
        fields[PANOS_FIELDS[name]] = value
    fields[0] = "1"
    fields[1] = fields[PANOS_FIELDS["generated_time"]]  # receive time
    fields[2] = "012801000001"  # serial number
    ts = event.timestamp
    header = f"<14>{ts:%b} {ts.day:>2} {ts:%H:%M:%S} {event.device}"
    return f"{header} {','.join(fields)}"


_FORTI_PROTO_NUMBERS = {"icmp": 1, "tcp": 6, "udp": 17}


def fortigate_line(rule: Rule, event: LogEvent, rng: random.Random) -> str:
    ts = event.timestamp
    if event.action is Action.ALLOW:
        action = rng.choice(["close", "close", "close", "timeout", "client-rst"])
    else:
        action = "deny"
    sent = event.bytes // 3
    parts = [
        f"<189>date={ts:%Y-%m-%d} time={ts:%H:%M:%S}",
        f'devname="{event.device}" devid="FGT60FTK00000001" logid="0000000013"',
        'type="traffic" subtype="forward" level="notice" vd="root"',
        f"srcip={event.src_ip} srcport={rng.randint(1024, 65535)}",
        f'srcintf="{_zone(rule.src_zones)}" dstip={event.dst_ip}',
        *([f"dstport={event.dst_port}"] if event.dst_port is not None else []),
        f'dstintf="{_zone(rule.dst_zones)}" proto={_FORTI_PROTO_NUMBERS[event.protocol]}',
        f'action="{action}" policyid={rule.vendor_id}',
        # FortiOS only logs policyname when the policy has one (name fell back to the ID).
        *([f'policyname="{rule.name}"'] if rule.name != rule.vendor_id else []),
        f"sentbyte={sent} rcvdbyte={event.bytes - sent}",
    ]
    return " ".join(parts)


def _zone(zones: tuple[str, ...]) -> str:
    return "any" if zones == (ANY,) else zones[0]


def render(
    config: ParsedConfig,
    pairs: list[tuple[Rule, LogEvent]],
    rng: random.Random,
) -> list[str]:
    """Log lines for a device, with realistic noise the parser must skip."""
    lines = []
    for rule, event in pairs:
        if config.vendor is Vendor.FORTIGATE:
            lines.append(fortigate_line(rule, event, rng))
            continue
        # PAN-OS logs some sessions at start too; the parser must not count them twice.
        if event.action is Action.ALLOW and rng.random() < 0.1:
            lines.append(panos_line(event, subtype="start"))
        lines.append(panos_line(event))
    lines.insert(len(lines) // 2, _noise_line(config))
    lines.insert(len(lines) // 3, "<14>truncated line: the parser should warn and skip this")
    return lines


def _noise_line(config: ParsedConfig) -> str:
    """A valid non-traffic log line."""
    ts = WINDOW_START + WINDOW / 2
    if config.vendor is Vendor.PANOS:
        return (
            f"<14>{ts:%b} {ts.day:>2} {ts:%H:%M:%S} {config.device} "
            f"1,{ts:%Y/%m/%d %H:%M:%S},012801000001,SYSTEM,general,0,{ts:%Y/%m/%d %H:%M:%S}"
            ",,general,,0,0,general,informational,User admin logged in"
        )
    return (
        f'<189>date={ts:%Y-%m-%d} time={ts:%H:%M:%S} devname="{config.device}" '
        'logid="0100032001" type="event" subtype="system" level="information" '
        'msg="Administrator admin logged in successfully"'
    )


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def sample_configs() -> list[ParsedConfig]:
    return [
        parse_panos_file(SAMPLES / "panos" / "lab-fw01.xml"),
        parse_fortigate_file(SAMPLES / "fortigate" / "lab-fgt01.conf"),
    ]


def build_sample_logs() -> dict[str, list[str]]:
    """Log lines per device, from a fresh RNG each time (so output is reproducible)."""
    rng = random.Random(SEED)
    return {
        config.device: render(config, generate_events(config, rng), rng)
        for config in sample_configs()
    }


def main() -> None:
    out_dir = SAMPLES / "logs"
    out_dir.mkdir(parents=True, exist_ok=True)
    for device, lines in build_sample_logs().items():
        path = out_dir / f"{device}.log"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {len(lines)} lines to {path.relative_to(SAMPLES.parents[1])}")


if __name__ == "__main__":
    main()
